import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import path from 'node:path';
import {chromium} from 'playwright';

const base=process.argv[2]||'http://localhost:4013',output=path.resolve('private/wallet-dashboard-2026-10-25/browser');
const token=process.env.CAMPAIGN_ADMIN_TOKEN;
if(!token)throw new Error('CAMPAIGN_ADMIN_TOKEN is required for the read-only admin verification.');
await fs.mkdir(output,{recursive:true});
const browser=await chromium.launch({headless:true});
const context=await browser.newContext({viewport:{width:1440,height:1100},acceptDownloads:true});
if(process.env.VERCEL_TEST_COOKIES)await context.addCookies(JSON.parse(process.env.VERCEL_TEST_COOKIES));
const page=await context.newPage(),errors=[];
page.on('pageerror',error=>errors.push(error.message));
try{
  const denied=await context.request.get(base+'/api/admin/wallet-intelligence');
  assert.equal(denied.status(),404);assert.match(denied.headers()['cache-control'],/private.*no-store/);
  const invalid=await context.request.get(base+'/api/admin/wallet-intelligence',{headers:{'X-Campaign-Admin':'invalid-test-token'}});assert.equal(invalid.status(),404);
  const post=await context.request.post(base+'/api/admin/wallet-intelligence');assert.equal(post.status(),405);
  await page.goto(base+'/admin/campaign',{waitUntil:'domcontentloaded'});
  await page.getByRole('link',{name:'MINT INTELLIGENCE →',exact:true}).click();
  await page.getByRole('heading',{name:'Open your mint briefing.'}).waitFor();
  assert.equal(await page.getByRole('group',{name:'Funding summary'}).count(),0);
  await page.getByLabel('Campaign admin token',{exact:true}).fill(token);
  const responsePromise=page.waitForResponse(response=>response.url().endsWith('/api/admin/wallet-intelligence')&&response.status()===200);
  await page.getByRole('button',{name:'Open dashboard',exact:true}).click();
  const response=await responsePromise,snapshot=await response.json();
  assert.equal(snapshot.wallets.length,8442);assert.equal(new Set(snapshot.wallets.map(w=>w.address)).size,8442);
  assert.equal(snapshot.wallets.filter(w=>w.app).length,2635);
  const summary=page.getByRole('group',{name:'Funding summary'});
  await summary.waitFor();
  const values=()=>summary.locator('strong').allTextContents();
  assert.deepEqual(await values(),['5,846','567','1,281','1,324']);
  assert(await page.getByRole('heading',{name:'654 units beyond supply if all GTD wallets claim.'}).isVisible());
  await page.screenshot({path:path.join(output,'desktop.png'),fullPage:true});
  await page.getByLabel('Analyze this audience').selectOption('pending-new');
  assert.deepEqual(await values(),['2,596','7','10','11']);
  await page.getByLabel('Application review period').selectOption('review_after_protection');
  assert(Number((await values())[0].replaceAll(',',''))<2596);
  await page.getByLabel('Application review period').selectOption('all');
  await page.getByLabel('Mint price · ETH',{exact:true}).fill('0.001');
  assert(Number((await values())[1].replaceAll(',',''))>7);
  await page.getByLabel('Mint price · ETH',{exact:true}).fill('0.01');
  await page.getByLabel('Total collection supply').fill('0');
  assert.match(await page.getByRole('alert').filter({hasText:'Supply and wallet caps'}).textContent(),/Supply and wallet caps/);
  await page.getByLabel('Total collection supply').fill('2048');
  await page.getByLabel('Team / other reserve').fill('500');
  assert(await page.getByRole('heading',{name:'1,154 units beyond supply if all GTD wallets claim.'}).isVisible());
  await page.getByLabel('Team / other reserve').fill('0');
  await page.getByLabel('GTD total cap / wallet').fill('2');
  assert(await page.getByRole('heading',{name:'3,356 units beyond supply if all GTD wallets claim.'}).isVisible());
  await page.getByLabel('GTD total cap / wallet').fill('1');
  const applicant=snapshot.wallets.find(w=>w.app&&!w.gtd&&!w.fcfs);
  await page.getByLabel('Find wallet or source').fill(applicant.address);
  assert(await page.getByText('1 matching wallets · page 1 of 1',{exact:true}).isVisible());
  const downloadPromise=page.waitForEvent('download');await page.getByRole('button',{name:'Export 1 filtered wallets',exact:true}).click();
  const download=await downloadPromise,file=path.join(output,'filtered-wallet.csv');await download.saveAs(file);
  const csv=await fs.readFile(file,'utf8');assert(csv.includes(applicant.address));assert.equal(csv.trim().split('\r\n').length,2);
  await page.locator('#wallets summary').first().click();
  assert.equal(await page.getByRole('link',{name:'Open application review →'}).getAttribute('href'),'/admin/wl?address='+applicant.address);
  await page.getByLabel('Find wallet or source').fill('');await page.getByLabel('Analyze this audience').selectOption('eligible');
  await page.setViewportSize({width:390,height:844});await page.evaluate(()=>window.scrollTo(0,0));
  assert(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth));
  await page.screenshot({path:path.join(output,'mobile.png'),fullPage:true});
  await page.getByRole('button',{name:'Lock dashboard'}).click();
  assert.equal(await page.getByRole('group',{name:'Funding summary'}).count(),0);
  assert.equal(await page.getByLabel('Campaign admin token',{exact:true}).inputValue(),'');
  assert.equal(await page.evaluate(value=>JSON.stringify(localStorage).includes(value)||JSON.stringify(sessionStorage).includes(value),token),false);
  assert.deepEqual(errors,[]);
  const result={verified:true,base,wallets:snapshot.wallets.length,applications:2635,authDenial:true,realApi:true,scenarioControls:true,filters:true,csv:true,desktop:true,mobile:true,lock:true,javascriptErrors:0};
  await fs.writeFile(path.join(output,'verification.json'),JSON.stringify(result,null,2)+'\n');console.log(JSON.stringify(result));
}finally{await browser.close();}
