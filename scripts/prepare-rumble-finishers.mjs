/** Pack generated transparent finisher poses; preserve their authored pixels. */
import fs from 'node:fs/promises';
import sharp from 'sharp';
const roster={};
for(const id of ['max','diamond','brian','mia','bernie','chloe']){
  const source=`public/arcade/fighters/${id}-finisher-poses-v1.png`;
  const {data,info}=await sharp(source).ensureAlpha().raw().toBuffer({resolveWithObject:true});
  const {width:w,height:h}=info,seen=new Uint8Array(w*h),parts=[];
  for(let n=0;n<w*h;n++){
    if(seen[n]||data[n*4+3]<32)continue;
    const pixels=[n];seen[n]=1;let left=w,right=0,top=h,bottom=0;
    for(let i=0;i<pixels.length;i++){
      const p=pixels[i],x=p%w,y=Math.floor(p/w);left=Math.min(left,x);right=Math.max(right,x);top=Math.min(top,y);bottom=Math.max(bottom,y);
      for(const dy of [-1,0,1])for(const dx of [-1,0,1]){const xx=x+dx,yy=y+dy,k=yy*w+xx;if(xx<0||xx>=w||yy<0||yy>=h||seen[k]||data[k*4+3]<32)continue;seen[k]=1;pixels.push(k);}
    }
    parts.push({pixels,left,right,top,bottom});
  }
  const bodies=parts.filter(p=>p.pixels.length>20000).sort((a,b)=>a.left-b.left);
  if(bodies.length!==3)throw Error(`${id}: expected three isolated poses, got ${bodies.length}`);
  for(const part of parts.filter(p=>p.pixels.length<=20000&&p.pixels.length>=5)){
    const x=(part.left+part.right)/2,y=(part.top+part.bottom)/2;
    const distance=b=>Math.hypot(Math.max(b.left-x,0,x-b.right),Math.max(b.top-y,0,y-b.bottom));
    const body=[...bodies].sort((a,b)=>distance(a)-distance(b))[0];
    if(distance(body)>90)continue;
    body.pixels.push(...part.pixels);body.left=Math.min(body.left,part.left);body.right=Math.max(body.right,part.right);body.top=Math.min(body.top,part.top);body.bottom=Math.max(body.bottom,part.bottom);
  }
  let x=8,height=0;const frames=[],tiles=[];
  for(const [i,b]of bodies.entries()){
    const width=b.right-b.left+5,h=b.bottom-b.top+5,pixels=Buffer.alloc(width*h*4);
    for(const n of b.pixels){const xx=n%w-b.left+2,yy=Math.floor(n/w)-b.top+2;data.copy(pixels,(yy*width+xx)*4,n*4,n*4+4);}
    tiles.push({input:await sharp(pixels,{raw:{width,height:h,channels:4}}).png().toBuffer(),left:x,top:8});
    const pivot=i===1?{max:.5,diamond:.32,brian:.45,mia:.3,bernie:.4,chloe:.32}[id]:.5;
    frames.push({name:['windup','impact','victory'][i],x,y:8,width,height:h,pivotX:Math.round(width*pivot),footY:h-2});
    x+=width+8;height=Math.max(height,h+16);
  }
  const src=`/arcade/fighters/${id}-finisher-atlas-v1.webp`;
  await sharp({create:{width:x,height,channels:4,background:'#00000000'}}).composite(tiles).webp({lossless:true}).toFile('public'+src);
  roster[id]={src,width:x,height,worldHeight:240,referenceHeight:frames[2].height,frames};
  console.log(`${id}: three finisher poses, ${x} × ${height}`);
}
await fs.writeFile('lib/arcade/rumble-finisher-sprite-data.mjs','// Generated by scripts/prepare-rumble-finishers.mjs.\nexport const FINISHER_SPRITES = '+JSON.stringify(roster,null,2)+';\n');
