/** Pack the nine illustrated poses without repainting or rescaling their pixels.
 * Connected components prevent neighboring poses leaking across uneven grids.
 */
import fs from 'node:fs/promises';
import sharp from 'sharp';
const names=['idle','punch','kick','special','sweep','air','hit','guard','victory'];
const pivots=[.5,.4,.27,.43,.35,.36,.55,.5,.5];
const roster={};
for(const id of ['max','diamond','brian','mia','bernie','chloe']){
  const version=id==='mia'?'v2':'v1';
  const {data,info}=await sharp(`public/arcade/fighters/${id}-poses-${version}.png`).ensureAlpha().raw().toBuffer({resolveWithObject:true});
  const {width:w,height:h}=info,owner=new Int32Array(w*h).fill(-1),parts=[];
  for(let n=0;n<w*h;n++){
    if(owner[n]>=0||data[n*4+3]<32)continue;
    const index=parts.length,q=[n];owner[n]=index;let left=w,right=0,top=h,bottom=0;
    for(let head=0;head<q.length;head++){
      const p=q[head],x=p%w,y=Math.floor(p/w);left=Math.min(left,x);right=Math.max(right,x);top=Math.min(top,y);bottom=Math.max(bottom,y);
      for(const dy of [-1,0,1])for(const dx of [-1,0,1]){
        const xx=x+dx,yy=y+dy,k=yy*w+xx;
        if(xx<0||xx>=w||yy<0||yy>=h||owner[k]>=0||data[k*4+3]<32)continue;
        owner[k]=index;q.push(k);
      }
    }
    parts.push({index,left,top,right,bottom,count:q.length,pixels:q});
  }
  const bodies=parts.filter(p=>p.count>10000);
  if(bodies.length!==9)throw new Error(`${id}: expected nine separate poses, got ${bodies.length}`);
  for(const body of bodies){body.pose=Math.floor((body.top+body.bottom)/2/(h/3))*3+Math.floor((body.left+body.right)/2/(w/3));}
  bodies.sort((a,b)=>a.pose-b.pose);
  if(new Set(bodies.map(b=>b.pose)).size!==9)throw new Error(`${id}: ambiguous layout`);
  // Keep detached details such as ice shards with the nearest body. Main body
  // ownership wins even where two poses' rectangular bounding boxes overlap.
  for(const part of parts.filter(p=>p.count<=10000)){
    if(part.count<5)continue;
    const x=(part.left+part.right)/2,y=(part.top+part.bottom)/2;
    const distance=b=>Math.hypot(Math.max(b.left-x,0,x-b.right),Math.max(b.top-y,0,y-b.bottom))+.001*Math.hypot(x-(b.left+b.right)/2,y-(b.top+b.bottom)/2);
    const body=[...bodies].sort((a,b)=>distance(a)-distance(b))[0];
    if(distance(body)>45)continue;
    body.pixels.push(...part.pixels);body.left=Math.min(body.left,part.left);body.right=Math.max(body.right,part.right);body.top=Math.min(body.top,part.top);body.bottom=Math.max(body.bottom,part.bottom);
  }
  const tiles=[],frames=[];let atlasWidth=0,atlasHeight=8;
  for(let row=0;row<3;row++){
    let x=8,rowHeight=0;
    for(let col=0;col<3;col++){
      const b=bodies[row*3+col],width=b.right-b.left+5,height=b.bottom-b.top+5,pixels=Buffer.alloc(width*height*4);
      for(const n of b.pixels){const xx=n%w-b.left+2,yy=Math.floor(n/w)-b.top+2;data.copy(pixels,(yy*width+xx)*4,n*4,n*4+4);}
      const input=await sharp(pixels,{raw:{width,height,channels:4}}).png().toBuffer();tiles.push({input,left:x,top:atlasHeight});
      frames.push({name:names[b.pose],x,y:atlasHeight,width,height,pivotX:Math.round(width*pivots[b.pose]),footY:height-2});
      x+=width+8;rowHeight=Math.max(rowHeight,height);
    }
    atlasWidth=Math.max(atlasWidth,x);atlasHeight+=rowHeight+8;
  }
  await sharp({create:{width:atlasWidth,height:atlasHeight,channels:4,background:'#00000000'}}).composite(tiles).webp({lossless:true}).toFile(`public/arcade/fighters/${id}-atlas-${version}.webp`);
  roster[id]={src:`/arcade/fighters/${id}-atlas-${version}.webp`,width:atlasWidth,height:atlasHeight,worldHeight:220,frames};
  console.log(`${id}: nine isolated poses, ${atlasWidth} × ${atlasHeight}`);
}
await fs.writeFile('lib/arcade/rumble-sprite-data.mjs','// Generated by scripts/prepare-rumble-sprites.mjs. Original illustration pixels, no rescaling.\nexport const RUMBLE_SPRITES = '+JSON.stringify(roster,null,2)+';\n');
