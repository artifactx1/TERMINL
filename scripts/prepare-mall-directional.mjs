/** Pack the authored directional poses; keep alpha, anatomical scale and foot anchors. */
import sharp from 'sharp';
import fs from 'node:fs/promises';
const catalog=JSON.parse(await fs.readFile('docs/mall-rat-directional-prompts.json','utf8'));
const roster={},pending=[];
for(const asset of catalog.assets){
 const {data,info}=await sharp(asset.source).ensureAlpha().raw().toBuffer({resolveWithObject:true}),{width:w,height:h}=info;
 const seen=new Uint8Array(w*h),parts=[];
 for(let n=0;n<w*h;n++){
  if(seen[n]||data[n*4+3]<32)continue;
  const pixels=[n];seen[n]=1;let l=w,t=h,r=0,b=0;
  for(let j=0;j<pixels.length;j++){
   const p=pixels[j],x=p%w,y=Math.floor(p/w);l=Math.min(l,x);r=Math.max(r,x);t=Math.min(t,y);b=Math.max(b,y);
   for(const dy of [-1,0,1])for(const dx of [-1,0,1]){const xx=x+dx,yy=y+dy,k=yy*w+xx;if(xx<0||xx>=w||yy<0||yy>=h||seen[k]||data[k*4+3]<32)continue;seen[k]=1;pixels.push(k);}
  }
  parts.push({pixels,l,t,r,b});
 }
 const bodies=parts.filter(p=>p.pixels.length>4000);
 if(bodies.length!==15)throw Error(`${asset.id}: expected 15 separate poses, found ${bodies.length}`);
 for(const body of bodies)body.cell=Math.floor((body.l+body.r)/2/(w/3))+Math.floor((body.t+body.b)/2/(h/5))*3;
 if(new Set(bodies.map(b=>b.cell)).size!==15||bodies.some(b=>b.cell>14))throw Error(`${asset.id}: ambiguous pose layout`);
 // Detached smoke and small outfit details belong to the closest silhouette.
 for(const part of parts.filter(p=>p.pixels.length<=4000&&p.pixels.length>4)){
  const x=(part.l+part.r)/2,y=(part.t+part.b)/2,d=p=>Math.hypot(Math.max(p.l-x,0,x-p.r),Math.max(p.t-y,0,y-p.b));
  const body=[...bodies].sort((a,b)=>d(a)-d(b))[0];if(d(body)>35)continue;
  body.l=Math.min(body.l,part.l);body.r=Math.max(body.r,part.r);body.t=Math.min(body.t,part.t);body.b=Math.max(body.b,part.b);
 }
 bodies.sort((a,b)=>a.cell-b.cell);
 const scale=Math.min(1,286/Math.max(...bodies.map(b=>Math.max(b.r-b.l+5,b.b-b.t+5)))),tiles=[],frames=[];
 for(const body of bodies){
  const width=body.r-body.l+5,height=body.b-body.t+5,left=body.l-2,top=body.t-2;
  if(left<0||top<0||left+width>w||top+height>h)throw Error(`${asset.id}: pose touches source edge`);
  // Arms can extend far to one side. Anchor on the feet, not the image midpoint.
  let footL=w,footR=0;
  for(let y=body.b-Math.ceil((body.b-body.t)*.08);y<=body.b;y++)for(let x=body.l;x<=body.r;x++)if(data[(y*w+x)*4+3]>128){footL=Math.min(footL,x);footR=Math.max(footR,x);}
  const outW=Math.round(width*scale),outH=Math.round(height*scale),x=body.cell%3*320+16,y=Math.floor(body.cell/3)*320+16;
  tiles.push({input:await sharp(asset.source).extract({left,top,width,height}).resize(outW,outH).png().toBuffer(),left:x,top:y});
  frames.push({name:`${catalog.layout.views[body.cell%3]}-${catalog.layout.rows[Math.floor(body.cell/3)]}`,x,y,width:outW,height:outH,footX:Math.round(((footL+footR)/2-left)*outW/width),footY:outH-3});
 }
 const buffer=await sharp({create:{width:960,height:1600,channels:4,background:'#00000000'}}).composite(tiles).webp({quality:93,alphaQuality:100}).toBuffer();
 pending.push({path:asset.atlas,buffer});
 roster[asset.id]={src:'/'+asset.atlas.replace(/^public\//,''),width:960,height:1600,frames};
 console.log(asset.id,frames.map(f=>`${f.name}:${f.width}x${f.height}@${f.footX}`).join(' '));
}
// Validate and pack the entire roster before replacing any generated outputs.
for(const asset of pending)await fs.writeFile(asset.path,asset.buffer);
await fs.writeFile('lib/arcade/after-hours/mall-directional-data.mjs','// Generated by scripts/prepare-mall-directional.mjs.\nexport const MALL_DIRECTIONAL = '+JSON.stringify(roster,null,2)+';\n');
